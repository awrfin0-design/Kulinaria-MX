import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const b = await chromium.launch();
const page = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
page.on('pageerror', (e) => console.log('ERR', e.message));
const U = 'file:///home/user/Kulinaria-MX/preview/index.html';
await page.addInitScript(() => { try { sessionStorage.setItem('kx-seen', '1'); if (!localStorage.getItem('kx-test-fresh')) localStorage.setItem('kulinaria_onboarded', '1'); } catch (e) {} });
await page.goto(U + '#/home'); await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); localStorage.setItem('kx-test-fresh', '1'); localStorage.setItem('kx-test-orders', '0'); });
await page.goto(U + '#/menu'); await page.reload(); await page.waitForTimeout(4200);
console.log(await page.evaluate(() => JSON.stringify({ url: location.href, acct: !!document.querySelector('#kx-account'), onb: localStorage.getItem('kulinaria_onboarded'), asked: sessionStorage.getItem('kx_ob_asked'), link: (document.querySelector('#kx-account [data-kx-onb]') || {}).outerHTML })));
await b.close();
